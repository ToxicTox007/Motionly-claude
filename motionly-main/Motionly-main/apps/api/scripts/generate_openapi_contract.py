#!/usr/bin/env python3
"""Generate the checked-in TypeScript API contract and OpenAPI artifact."""

import argparse
import json
import os
import re
import sys
from pathlib import Path
from typing import Any

API_ROOT = Path(__file__).resolve().parents[1]
REPO_ROOT = API_ROOT.parents[1]
OUTPUT = REPO_ROOT / "packages/shared/src/generated/api.ts"
OPENAPI_OUTPUT = REPO_ROOT / "packages/shared/openapi.json"
HTTP_METHODS = ("get", "post", "put", "patch", "delete")


def schema_type(schema: dict[str, Any] | None) -> str:
    if not schema:
        return "unknown"
    if "$ref" in schema:
        return f'components["schemas"]["{schema["$ref"].rsplit("/", 1)[-1]}"]'
    if "const" in schema:
        return json.dumps(schema["const"])
    if schema.get("enum") is not None:
        values = schema["enum"]
        return " | ".join(json.dumps(value) for value in values) or "never"
    for combinator, separator in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
        if combinator in schema:
            return separator.join(schema_type(item) for item in schema[combinator])
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(schema_type({**schema, "type": item}) for item in kind)
    if kind == "array":
        return f"Array<{schema_type(schema.get('items'))}>"
    if kind == "object" or "properties" in schema or "additionalProperties" in schema:
        properties = schema.get("properties") or {}
        required = set(schema.get("required") or [])
        members = []
        for name, value in properties.items():
            key = name if re.fullmatch(r"[A-Za-z_$][\w$]*", name) else json.dumps(name)
            members.append(f"{key}{'' if name in required else '?'}: {schema_type(value)};")
        additional = schema.get("additionalProperties")
        if additional is True:
            members.append("[key: string]: unknown;")
        elif isinstance(additional, dict):
            members.append(f"[key: string]: {schema_type(additional)};")
        return "{ " + " ".join(members) + " }"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(str(kind), "unknown")


def operation_type(path: str, method: str, operation: dict[str, Any]) -> str:
    parameters = operation.get("parameters") or []
    path_parameters = {
        item["name"]: schema_type(item.get("schema"))
        for item in parameters
        if item.get("in") == "path"
    }
    query_parameters = {
        item["name"]: (schema_type(item.get("schema")), bool(item.get("required")))
        for item in parameters
        if item.get("in") == "query"
    }
    body_schema = None
    content = (operation.get("requestBody") or {}).get("content") or {}
    for media_type in ("application/json", "multipart/form-data", "application/octet-stream"):
        if media_type in content:
            body_schema = content[media_type].get("schema")
            break
    responses = operation.get("responses") or {}
    success = next(
        (responses[code] for code in sorted(responses) if str(code).startswith("2")),
        {},
    )
    response_content = success.get("content") or {}
    response_schema = next(
        (entry.get("schema") for entry in response_content.values() if entry.get("schema")),
        None,
    )
    path_shape = (
        "{ "
        + " ".join(f"{key}: {value};" for key, value in path_parameters.items())
        + " }"
    )
    query_shape = "{ " + " ".join(
        f"{key}{'' if required else '?'}: {value};"
        for key, (value, required) in query_parameters.items()
    ) + " }"
    return (
        "{ "
        f"method: {json.dumps(method.upper())}; template: {json.dumps(path)}; "
        f"path: {path_shape}; query: {query_shape}; "
        f"body: {schema_type(body_schema) if body_schema else 'never'}; "
        f"response: {schema_type(response_schema) if response_schema else 'void'}; "
        "}"
    )


def generate(openapi: dict[str, Any]) -> str:
    schemas = openapi.get("components", {}).get("schemas", {})
    lines = [
        "/* eslint-disable */",
        "// Generated by apps/api/scripts/generate_openapi_contract.py. Do not edit.",
        "",
        "export interface components {",
        "  schemas: {",
    ]
    for name in sorted(schemas):
        lines.append(f'    "{name}": {schema_type(schemas[name])};')
    lines.extend(["  };", "}", "", "export interface ApiOperationMap {"])
    for path in sorted(openapi.get("paths", {})):
        path_item = openapi["paths"][path]
        for method in HTTP_METHODS:
            if method in path_item:
                key = f"{method.upper()} {path}"
                lines.append(f'  "{key}": {operation_type(path, method, path_item[method])};')
    lines.extend(
        [
            "}",
            "",
            "export type ApiOperation = keyof ApiOperationMap;",
            "export type ApiResponse<K extends ApiOperation> = ApiOperationMap[K][\"response\"];",
            "export type ApiRequest<K extends ApiOperation> = {",
            "  path: ApiOperationMap[K][\"path\"];",
            "  query?: ApiOperationMap[K][\"query\"];",
            "  body?: ApiOperationMap[K][\"body\"];",
            "  headers?: HeadersInit;",
            "};",
            "",
            "export async function apiRequest<K extends ApiOperation>(",
            "  baseUrl: string,",
            "  operation: K,",
            "  options: ApiRequest<K>,",
            "): Promise<ApiResponse<K>> {",
            "  const [method, ...templateParts] = operation.split(\" \");",
            '  let path = templateParts.join(" ");',
            "  for (const [key, value] of Object.entries(options.path ?? {})) {",
            "    path = path.replace(`{${key}}`, encodeURIComponent(String(value)));",
            "  }",
            '  const root = baseUrl.endsWith("/") ? baseUrl : `${baseUrl}/`;',
            "  const url = new URL(path, root);",
            "  for (const [key, value] of Object.entries(options.query ?? {})) {",
            (
                "    if (value !== undefined && value !== null) "
                "url.searchParams.set(key, String(value));"
            ),
            "  }",
            "  const response = await fetch(url, {",
            "    method,",
            "    headers: { \"content-type\": \"application/json\", ...options.headers },",
            "    body: options.body === undefined ? undefined : JSON.stringify(options.body),",
            "  });",
            (
                "  if (!response.ok) throw new Error("
                "`Motionly API ${operation} failed: ${response.status}`);"
            ),
            "  if (response.status === 204) return undefined as ApiResponse<K>;",
            "  return await response.json() as ApiResponse<K>;",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    os.environ.setdefault("APP_ENV", "test")
    os.environ.setdefault("ALLOW_FIXTURE_PROVIDERS", "true")
    sys.path.insert(0, str(API_ROOT))
    from app.main import app

    openapi = app.openapi()
    contract = generate(openapi)
    openapi_text = json.dumps(openapi, indent=2, sort_keys=True) + "\n"
    if args.check:
        stale = []
        if not OUTPUT.exists() or OUTPUT.read_text() != contract:
            stale.append(str(OUTPUT.relative_to(REPO_ROOT)))
        if not OPENAPI_OUTPUT.exists() or OPENAPI_OUTPUT.read_text() != openapi_text:
            stale.append(str(OPENAPI_OUTPUT.relative_to(REPO_ROOT)))
        if stale:
            print("Generated API contracts are stale: " + ", ".join(stale), file=sys.stderr)
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(contract)
    OPENAPI_OUTPUT.write_text(openapi_text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
